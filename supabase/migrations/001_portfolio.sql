create table if not exists public.projects (
  id bigint generated by default as identity primary key,
  title text not null,
  category text not null,
  image text not null,
  problem text not null,
  solution text not null,
  architecture text not null,
  contribution text[] not null default '{}',
  results text[] not null default '{}',
  technologies text[] not null default '{}',
  live_url text not null default '#',
  github_url text not null,
  sort_order integer not null default 0,
  is_published boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.skill_groups (
  id bigint generated by default as identity primary key,
  category text not null,
  icon text not null check (icon in ('cloud', 'layout', 'database', 'tool')),
  skills text[] not null default '{}',
  sort_order integer not null default 0,
  is_published boolean not null default true
);

create table if not exists public.experiences (
  id bigint generated by default as identity primary key,
  title text not null,
  company text not null,
  location text not null,
  period text not null,
  description text not null,
  technologies text[] not null default '{}',
  sort_order integer not null default 0,
  is_published boolean not null default true
);

create table if not exists public.education (
  id bigint generated by default as identity primary key,
  degree text not null,
  field text not null,
  school text not null,
  period text not null,
  description text not null,
  sort_order integer not null default 0,
  is_published boolean not null default true
);

create table if not exists public.social_links (
  id bigint generated by default as identity primary key,
  label text not null,
  href text not null,
  sort_order integer not null default 0,
  is_published boolean not null default true
);

create table if not exists public.nav_items (
  id bigint generated by default as identity primary key,
  label text not null,
  href text not null,
  sort_order integer not null default 0,
  is_published boolean not null default true
);

create table if not exists public.devops_lifecycle (
  id bigint generated by default as identity primary key,
  step text not null,
  title text not null,
  description text not null,
  image text not null,
  color text not null,
  sort_order integer not null default 0,
  is_published boolean not null default true
);

create table if not exists public.contact_submissions (
  id bigint generated by default as identity primary key,
  reference text not null unique,
  name text not null,
  email text not null,
  subject text not null,
  message text not null,
  ip_address inet,
  created_at timestamptz not null default now(),
  status text not null default 'new' check (status in ('new', 'read', 'replied', 'archived'))
);

create index if not exists projects_published_order_idx on public.projects (is_published, sort_order);
create index if not exists skill_groups_published_order_idx on public.skill_groups (is_published, sort_order);
create index if not exists experiences_published_order_idx on public.experiences (is_published, sort_order);
create index if not exists education_published_order_idx on public.education (is_published, sort_order);
create index if not exists social_links_published_order_idx on public.social_links (is_published, sort_order);
create index if not exists nav_items_published_order_idx on public.nav_items (is_published, sort_order);
create index if not exists contact_submissions_created_at_idx on public.contact_submissions (created_at desc);

